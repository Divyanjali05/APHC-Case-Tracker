"""Database models for Case Voice Notes and Speech-to-Text Transcriptions."""

from __future__ import annotations

from django.conf import settings
from django.db import models
from django.utils import timezone

from apps.cases.models import Case

from .storage import secure_voice_storage, voice_note_upload_path


class TranscriptionStatus(models.TextChoices):
    NOT_STARTED = "NOT_STARTED", "Not Started"
    PROCESSING = "PROCESSING", "Processing"
    COMPLETED = "COMPLETED", "Completed"
    FAILED = "FAILED", "Failed"


class TranscriptionLanguage(models.TextChoices):
    ENGLISH = "en", "English"
    TELUGU = "te", "Telugu"
    HINDI = "hi", "Hindi"


class VoiceNote(models.Model):
    """Advocate voice dictation and client preparation audio recording linked to a case."""

    case = models.ForeignKey(Case, on_delete=models.CASCADE, related_name="voice_notes")
    advocate = models.ForeignKey(
        settings.AUTH_USER_MODEL, on_delete=models.CASCADE, related_name="voice_notes"
    )
    title = models.CharField(max_length=200)
    audio_file = models.FileField(storage=secure_voice_storage, upload_to=voice_note_upload_path)
    audio_duration_seconds = models.FloatField(default=0.0)
    audio_file_size_bytes = models.PositiveIntegerField(default=0)
    audio_mime_type = models.CharField(max_length=100, default="audio/m4a")

    transcription_status = models.CharField(
        max_length=30,
        choices=TranscriptionStatus.choices,
        default=TranscriptionStatus.NOT_STARTED,
    )
    transcription_language = models.CharField(
        max_length=10,
        choices=TranscriptionLanguage.choices,
        default=TranscriptionLanguage.ENGLISH,
    )
    original_transcript = models.TextField(
        blank=True,
        default="",
        help_text="Immutable original speech recognition transcript",
    )
    transcript = models.TextField(
        blank=True,
        default="",
        help_text="Editable advocate transcription text",
    )
    transcription_provider = models.CharField(max_length=100, default="MOCK_STT_PROVIDER")
    is_mock = models.BooleanField(
        default=True,
        help_text="True if generated by mock/test STT engine; False if official live provider",
    )
    transcription_error = models.TextField(blank=True, default="")
    transcribed_at = models.DateTimeField(null=True, blank=True)

    recorded_at = models.DateTimeField(default=timezone.now)
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-recorded_at", "-created_at"]
        indexes = [
            models.Index(fields=["case", "-recorded_at"]),
            models.Index(fields=["advocate", "-created_at"]),
        ]

    def __str__(self) -> str:
        return f"VoiceNote: {self.title} ({self.case}) by {self.advocate.username}"

    def delete(self, *args, **kwargs):
        # Securely delete physical audio file from disk
        if self.audio_file:
            try:
                self.audio_file.close()
            except Exception:
                pass
            try:
                self.audio_file.delete(save=False)
            except Exception:
                pass
        super().delete(*args, **kwargs)
